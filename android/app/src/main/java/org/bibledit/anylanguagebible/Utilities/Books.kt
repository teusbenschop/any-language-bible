// Returns the optional identifier for a given book name.
fun bookId(name: String): Int? =
    books.firstOrNull { it.english == name }?.id

// Returns the optional English book name for a given book identifier.
fun bookName(id: Int): String? =
    books.firstOrNull { it.id == id }?.english
